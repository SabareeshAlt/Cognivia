# ─── AGENT 8: RESPONSE LATENCY PROFILER ───
def run_latency_profiling() -> Dict[str, Any]:
    print("Agent 8: Profiling response latency and token throughput...")
    if not RAG_AVAILABLE:
        return {"status": "error", "message": "RAG module not available"}
        
    dataset_path = PROJECT_ROOT / "eval" / "golden_set_academic.json"
    if not dataset_path.exists():
        return {"status": "error", "message": "Dataset not found"}
        
    with open(dataset_path, "r", encoding="utf-8") as f:
        dataset = json.load(f)
        
    latencies = []
    ttfts = []
    tokens_per_sec = []
    
    for case in dataset[:3]:  # Profile on 3 cases
        q = case["question"]
        print(f"  Profiling query: '{q[:40]}...'")
        
        start_time = time.perf_counter()
        stream = stream_optimized_response(q)
        
        first_token_time = None
        chars_generated = 0
        
        for event in stream:
            # Parse event payload to extract generated characters
            if first_token_time is None:
                first_token_time = time.perf_counter()
            if "data: " in event:
                try:
                    payload = json.loads(event.replace("data: ", "").strip())
                    if payload.get("type") == "token":
                        chars_generated += len(payload.get("content", ""))
                except Exception:
                    pass
                    
        end_time = time.perf_counter()
        
        total_latency = (end_time - start_time) * 1000  # ms
        ttft = ((first_token_time or end_time) - start_time) * 1000  # ms
        
        # Estimate token count (4 chars = 1 token approx)
        est_tokens = max(1, chars_generated // 4)
        generation_duration = max(0.001, end_time - (first_token_time or start_time))
        tps = est_tokens / generation_duration
        
        latencies.append(total_latency)
        ttfts.append(ttft)
        tokens_per_sec.append(tps)
        
    summary = {
        "mean_latency_ms": statistics.mean(latencies),
        "mean_ttft_ms": statistics.mean(ttfts),
        "mean_tokens_per_second": statistics.mean(tokens_per_sec),
        "total_cases_profiled": len(latencies)
    }
    
    reports_dir = PROJECT_ROOT / "eval" / "multi_agent" / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    with open(reports_dir / "latency_report.json", "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
        
    print(f"Latency profile saved to {reports_dir / 'latency_report.json'}")
    return summary


