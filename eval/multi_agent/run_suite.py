class OllamaJudge:
    def __init__(self, model="gemma4:latest", endpoint="http://localhost:11434/api/generate"):
        self.model = model
        self.endpoint = endpoint

    def call_llm(self, prompt: str) -> str:
        import requests
        payload = {
            "model": self.model,
            "prompt": prompt,
            "stream": False,
            "options": {"temperature": 0.0}
        }
        try:
            response = requests.post(self.endpoint, json=payload, timeout=90)
            response.raise_for_status()
            return response.json().get("response", "").strip()
        except Exception as e:
            print(f"Ollama call error: {e}")
            return "0"

    def extract_numeric_score(self, response: str) -> float:
        # Match float or int (e.g. 0.85, 1, 0)
        match = re.search(r'\b(0?\.\d+|1\.0|0\.0|1|0)\b', response)
        if match:
            try:
                return float(match.group(1))
            except ValueError:
                pass
        return 0.0


# ─── AGENT 1: ARCHITECTURE AUDIT ───
def run_architecture_audit() -> Dict[str, Any]:
    print("Agent 1: Running codebase architecture audit and generating dependency graph...")
    modules = ["database", "rag", "api", "rag_project"]
    imports_map = {}
    file_list = []
    
    for mod in modules:
        mod_path = PROJECT_ROOT / mod
        if not mod_path.exists():
            continue
        for py_file in mod_path.rglob("*.py"):
            if py_file.name == "__init__.py" or "pycache" in str(py_file):
                continue
            file_list.append(py_file)
            rel_path = py_file.relative_to(PROJECT_ROOT).as_posix()
            imports_map[rel_path] = []
            
            # Simple AST/Regex parsing of imports
            try:
                content = py_file.read_text(encoding="utf-8")
                for line in content.splitlines():
                    # Match standard imports
                    m1 = re.match(r'^(?:from\s+([a-zA-Z0-9_\.]+)\s+import|import\s+([a-zA-Z0-9_\.]+))', line.strip())
                    if m1:
                        imp = m1.group(1) or m1.group(2)
                        # Keep only internal imports
                        for internal in modules:
                            if imp.startswith(internal):
                                imports_map[rel_path].append(imp)
            except Exception as e:
                print(f"Error parsing {py_file}: {e}")

    # Generate Mermaid chart
    mermaid_lines = ["graph TD"]
    for file, imps in imports_map.items():
        file_node = file.replace("/", "_").replace(".", "_")
        mermaid_lines.append(f'    {file_node}["{file}"]')
        for imp in imps:
            # Try to resolve module path to file node
            imp_parts = imp.split(".")
            resolved = None
            for i in range(len(imp_parts), 0, -1):
                test_path = "/".join(imp_parts[:i])
                # Check file or dir
                if (PROJECT_ROOT / f"{test_path}.py").exists():
                    resolved = f"{test_path}.py"
                    break
                elif (PROJECT_ROOT / test_path).is_dir():
                    resolved = f"{test_path}/__init__.py"
                    break
            if resolved:
                imp_node = resolved.replace("/", "_").replace(".", "_")
                mermaid_lines.append(f"    {file_node} --> {imp_node}")
    
    mermaid_code = "\n".join(mermaid_lines)
    
    report_md = f"""# Codebase Architecture Report & Dependency Graph
Generated by: Architecture & System Audit Agent (Agent 1)
Timestamp: {time.strftime("%Y-%m-%d %H:%M:%S")}

## Component Mapping
- **Database & Ingestion Layer**: Loading, parsing, chunking, and embedding PDFs. Vector DB (Zilliz / Milvus Lite) and BM25 setups.
- **RAG & Orchestration Layer**: Reranking, retrieval logic, prompting, provider failovers (Groq / Ollama).
- **Web API (Django)**: REST endpoints, tracking models, metrics, and health endpoints.
- **Frontend Layer**: TypeScript/React dashboard with client-side sanitization.

## System Dependency Graph
```mermaid
{mermaid_code}
```
"""
    
    reports_dir = PROJECT_ROOT / "eval" / "multi_agent" / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    (reports_dir / "architecture_report.md").write_text(report_md, encoding="utf-8")
    print(f"Architecture report successfully saved to {reports_dir / 'architecture_report.md'}")
    return {"status": "success", "files_audited": len(file_list)}


# ─── AGENT 2: RETRIEVAL EVALUATION ───
def run_retrieval_evaluation(k=5) -> Dict[str, Any]:
    print("Agent 2: Evaluating retrieval precision, recall, and MRR metrics...")
    if not RAG_AVAILABLE:
        return {"status": "error", "message": "RAG module not available"}
        
    dataset_path = PROJECT_ROOT / "eval" / "golden_set_academic.json"
    if not dataset_path.exists():
        return {"status": "error", "message": "Dataset not found"}
        
    with open(dataset_path, "r", encoding="utf-8") as f:
        dataset = json.load(f)
        
    results = []
    for case in dataset:
        q = case["question"]
        expected = case.get("expected_sources", [])
        
        docs = _retrieve_docs(q)
        retrieved_sources = [doc.metadata.get("source", "") for doc in docs[:k]]
        
        # Calculate hits
        hits = sum(1 for src in retrieved_sources if any(exp in src for exp in expected))
        
        precision = hits / len(retrieved_sources) if retrieved_sources else 0.0
        recall = hits / len(expected) if expected else (1.0 if not expected else 0.0)
        
        # MRR
        mrr = 0.0
        for rank, src in enumerate(retrieved_sources, 1):
            if any(exp in src for exp in expected):
                mrr = 1.0 / rank
                break
                
        results.append({
            "id": case["id"],
            "question": q,
            "expected_sources": expected,
            "retrieved_sources": retrieved_sources,
            "precision": precision,
            "recall": recall,
            "mrr": mrr
        })
        
    mean_p = statistics.mean([r["precision"] for r in results])
    mean_r = statistics.mean([r["recall"] for r in results])
    mean_mrr = statistics.mean([r["mrr"] for r in results])
    
    summary = {
        "mean_precision_at_k": mean_p,
        "mean_recall_at_k": mean_r,
        "mean_mrr": mean_mrr,
        "total_cases": len(results)
    }
    
    reports_dir = PROJECT_ROOT / "eval" / "multi_agent" / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    with open(reports_dir / "retrieval_report.json", "w", encoding="utf-8") as f:
        json.dump({"summary": summary, "results": results}, f, indent=2)
        
    print(f"Retrieval evaluation saved to {reports_dir / 'retrieval_report.json'}")
    return summary


# ─── AGENT 3: CITATION VALIDATION ───
def run_citation_validation() -> Dict[str, Any]:
    print("Agent 3: Validating generated citations against sources...")
    if not RAG_AVAILABLE:
        return {"status": "error", "message": "RAG module not available"}
        
    dataset_path = PROJECT_ROOT / "eval" / "golden_set_academic.json"
    if not dataset_path.exists():
        return {"status": "error", "message": "Dataset not found"}
        
    with open(dataset_path, "r", encoding="utf-8") as f:
        dataset = json.load(f)
        
    results = []
    total_citations = 0
    valid_citations = 0
    
    for case in dataset[:5]:  # Run on first 5 cases to conserve generation time
        q = case["question"]
        print(f"  Generating response for citation check: '{q[:40]}...'")
        answer = get_optimized_response(q)
        
        # Regex to find all citations e.g. [Source: RAG sample 1.pdf, Page: 4]
        citations = re.findall(r'\[Source:\s*([^,\]]+)(?:,\s*Page:?\s*(\d+))?\]', answer, re.IGNORECASE)
        
        case_citations = []
        for src, page in citations:
            total_citations += 1
            src_clean = src.strip()
            page_clean = page.strip() if page else None
            
            # Citation is valid if source PDF exists in documents/
            pdf_path = PROJECT_ROOT / "documents" / src_clean
            exists = pdf_path.exists()
            
            is_valid = exists
            if is_valid:
                valid_citations += 1
                
            case_citations.append({
                "source": src_clean,
                "page": page_clean,
                "source_exists": exists,
                "is_valid": is_valid
            })
            
        results.append({
            "id": case["id"],
            "question": q,
            "citations_found": len(citations),
            "citations": case_citations
        })
        
    accuracy = valid_citations / total_citations if total_citations else 1.0
    summary = {
        "total_citations_analyzed": total_citations,
        "valid_citations": valid_citations,
        "citation_accuracy": accuracy,
        "total_cases": len(results)
    }
    
    reports_dir = PROJECT_ROOT / "eval" / "multi_agent" / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    with open(reports_dir / "citations_report.json", "w", encoding="utf-8") as f:
        json.dump({"summary": summary, "results": results}, f, indent=2)
        
    print(f"Citation report saved to {reports_dir / 'citations_report.json'}")
    return summary


# ─── AGENT 4: RAGAS EVALUATION ───
def run_ragas_evaluation() -> Dict[str, Any]:
    print("Agent 4: Executing RAGAS LLM-as-a-judge quality scoring...")
    if not RAG_AVAILABLE:
        return {"status": "error", "message": "RAG module not available"}
        
    dataset_path = PROJECT_ROOT / "eval" / "golden_set_academic.json"
    if not dataset_path.exists():
        return {"status": "error", "message": "Dataset not found"}
        
    with open(dataset_path, "r", encoding="utf-8") as f:
        dataset = json.load(f)
        
    judge = OllamaJudge(model="gemma4:latest")
    results = []
    
    for case in dataset[:3]:  # Run on first 3 cases due to Ollama evaluation time
        q = case["question"]
        print(f"  Evaluating case: '{q[:40]}...'")
        docs = _retrieve_docs(q)
        context = _format_context(docs)
        answer = get_optimized_response(q)
        
        # 1. Faithfulness
        faithfulness_prompt = f"""
        Given the context and an answer, determine if the answer is faithful to the context.
        An answer is faithful if it ONLY contains claims directly supported by the context.
        If there are any unsubstantiated or hallucinated claims, score it 0.0. If perfectly faithful, score it 1.0.
        Otherwise, provide a score between 0.0 and 1.0 representing the proportion of statements that are faithful.
        
        Context: {context}
        Answer: {answer}
        
        Output only a single decimal number representing the score:
        """
        f_score = judge.extract_numeric_score(judge.call_llm(faithfulness_prompt))
        
        # 2. Answer Relevancy
        relevancy_prompt = f"""
        Given a question and an answer, rate how relevant the answer is to the question.
        Does the answer directly address and answer the question?
        Rate from 0.0 (totally irrelevant) to 1.0 (perfectly relevant and direct).
        
        Question: {q}
        Answer: {answer}
        
        Output only a single decimal number representing the score:
        """
        r_score = judge.extract_numeric_score(judge.call_llm(relevancy_prompt))
        
        # 3. Context Precision
        precision_prompt = f"""
        Given a question and context chunks, rate context precision.
        Is all retrieved context highly relevant and useful for answering the question?
        Rate from 0.0 (useless/noise) to 1.0 (completely relevant).
        
        Question: {q}
        Context: {context}
        
        Output only a single decimal number representing the score:
        """
        p_score = judge.extract_numeric_score(judge.call_llm(precision_prompt))
        
        results.append({
            "id": case["id"],
            "question": q,
            "faithfulness": f_score,
            "answer_relevancy": r_score,
            "context_precision": p_score
        })
        
    mean_faith = statistics.mean([r["faithfulness"] for r in results])
    mean_rel = statistics.mean([r["answer_relevancy"] for r in results])
    mean_prec = statistics.mean([r["context_precision"] for r in results])
    
    summary = {
        "mean_faithfulness": mean_faith,
        "mean_answer_relevancy": mean_rel,
        "mean_context_precision": mean_prec,
        "total_cases": len(results)
    }
    
    reports_dir = PROJECT_ROOT / "eval" / "multi_agent" / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    with open(reports_dir / "ragas_report.json", "w", encoding="utf-8") as f:
        json.dump({"summary": summary, "results": results}, f, indent=2)
        
    print(f"RAGAS report saved to {reports_dir / 'ragas_report.json'}")
    return summary


